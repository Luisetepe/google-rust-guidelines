#!/usr/bin/env python3
"""Regenerate the section README indexes from the chapter files, or check the repo.

Usage:
    python3 tools/gen_indexes.py           # rewrite <section>/README.md
    python3 tools/gen_indexes.py --check   # fail on stale indexes, broken links/anchors, ID problems
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SECTIONS = {
    "google": (
        "Google Rust Style Guide",
        "https://google.github.io/styleguide/rustguide.html",
        "Google's own Rust rules. Binding for library code; strong recommendation for application code. Overrides the Rust Style Guide and API Guidelines on conflict.",
    ),
    "rust-style-guide": (
        "The Rust Style Guide",
        "https://doc.rust-lang.org/nightly/style-guide/",
        "The default Rust style, enforced by `rustfmt`. Applies unless the Google guide overrides it (see **Google note** entries).",
    ),
    "api-guidelines": (
        "Rust API Guidelines",
        "https://rust-lang.github.io/api-guidelines/",
        "Library API design guidelines from the Rust library team. IDs are the upstream `C-XXX` IDs; this table doubles as the checklist.",
    ),
    "references": (
        "References",
        None,
        "Condensed notes on pages the Google guide links to: tooling, language concepts, and related guides.",
    ),
}
ANCHOR_RE = re.compile(r'^<a id="([^"]+)"></a>\s*$')
RULE_RE = re.compile(r"^## ([A-Z][A-Z0-9-]+) — (.+)$")
FENCE_RE = re.compile(r"^\s*```")


def chapters(section):
    return sorted(f for f in (ROOT / section).glob("*.md") if f.name != "README.md")


def title_of(path):
    for line in path.read_text().splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem


def field(lines, name):
    """Text of a `**Name:**` field, joined across its continuation lines."""
    for i, line in enumerate(lines):
        if line.startswith(f"**{name}:**"):
            parts = [line[len(name) + 5 :].strip()]
            for nxt in lines[i + 1 :]:
                if not nxt.strip() or nxt.startswith("**") or nxt.startswith("#"):
                    break
                parts.append(nxt.strip())
            return " ".join(parts)
    return ""


def entries(path):
    """(anchor, heading, rule_id, rule_text, applies_to) for every anchored `##` heading."""
    lines = path.read_text().splitlines()
    out, pending, in_fence = [], None, False
    for i, line in enumerate(lines):
        if FENCE_RE.match(line):
            in_fence = not in_fence
        if in_fence:
            continue
        m = ANCHOR_RE.match(line)
        if m:
            pending = m.group(1)
            continue
        if line.startswith("## ") and pending:
            end = next((j for j in range(i + 1, len(lines)) if lines[j].startswith("## ")), len(lines))
            body = lines[i + 1 : end]
            rule = RULE_RE.match(line)
            out.append(
                (
                    pending,
                    rule.group(2) if rule else line[3:].strip(),
                    rule.group(1) if rule else None,
                    field(body, "Rule"),
                    field(body, "Applies to").rstrip("."),
                )
            )
            pending = None
        elif line.strip():
            pending = None
    return out


def cell(text, filename):
    text = re.sub(r"\]\(#", f"]({filename}#", text)  # same-file anchors must point at the chapter
    return text.replace("|", "\\|")


def render_index(section):
    name, url, blurb = SECTIONS[section]
    files = chapters(section)
    out = [f"# {name}", ""]
    if url:
        out += [f"> **Source:** [{name}]({url})", ">"]
    out += [
        f"> {blurb}",
        "",
        "<!-- Generated by tools/gen_indexes.py from the chapter files. Do not edit by hand. -->",
        "",
        "## Chapters",
        "",
    ]
    for f in files:
        n = sum(1 for e in entries(f) if e[2])
        count = f" — {n} rule{'' if n == 1 else 's'}" if n else ""
        out.append(f"- [{title_of(f)}]({f.name}){count}")
    out.append("")
    for f in files:
        es = entries(f)
        if not es:
            continue
        out += [f"## [{title_of(f)}]({f.name})", "", "| ID | Title | Rule |", "| --- | --- | --- |"]
        for anchor, heading, rule_id, rule, applies in es:
            label = rule_id or f"`#{anchor}`"
            text = rule + (f" *Applies to: {applies}.*" if applies else "")
            out.append(f"| [{label}]({f.name}#{anchor}) | {cell(heading, f.name)} | {cell(text, f.name)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def slug(heading):
    """GitHub's heading anchor."""
    h = re.sub(r"<[^>]+>", "", heading)
    h = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", h).strip().lower()
    return re.sub(r"[^\w\- ]", "", h).replace(" ", "-")


def anchors(path):
    found, seen, in_fence = set(), {}, False
    for line in path.read_text().splitlines():
        if FENCE_RE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        found.update(re.findall(r'<a id="([^"]+)"></a>', line))
        m = re.match(r"^#{1,6} (.+)$", line)
        if m:
            s = slug(m.group(1))
            n = seen.get(s, 0)
            seen[s] = n + 1
            found.add(s if n == 0 else f"{s}-{n}")
    return found


def check():
    problems, ids, cache = [], {}, {}
    for section in SECTIONS:
        readme = ROOT / section / "README.md"
        if not readme.exists() or readme.read_text() != render_index(section):
            problems.append(f"{section}/README.md is stale: run python3 tools/gen_indexes.py")
    for path in sorted(ROOT.rglob("*.md")):
        if ".git" in path.parts:
            continue
        rel = path.relative_to(ROOT)
        lines = path.read_text().splitlines()
        if sum(1 for line in lines if FENCE_RE.match(line)) % 2:
            problems.append(f"{rel}: unbalanced code fences")
        prose, in_fence = [], False
        for i, line in enumerate(lines):
            if FENCE_RE.match(line):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            prose.append(re.sub(r"`[^`]*`", "", line))
            m = RULE_RE.match(line)
            if m and path.name != "README.md":
                ids.setdefault(m.group(1), []).append(str(rel))
                prev = next((x for x in reversed(lines[:i]) if x.strip()), "")
                if prev != f'<a id="{m.group(1).lower()}"></a>':
                    problems.append(f"{rel}:{i + 1}: {m.group(1)} must be preceded by its <a id> anchor")
        for target in re.findall(r"\]\(([^)\s]+)\)", "\n".join(prose)):
            if re.match(r"[a-z]+:", target):
                continue
            file_part, _, frag = target.partition("#")
            dest = (path.parent / file_part).resolve() if file_part else path
            if not dest.exists():
                problems.append(f"{rel}: missing file {target}")
                continue
            if frag and dest.suffix == ".md":
                if dest not in cache:
                    cache[dest] = anchors(dest)
                if frag not in cache[dest]:
                    problems.append(f"{rel}: missing anchor {target}")
    problems += [f"duplicate rule ID {rid}: {files}" for rid, files in ids.items() if len(files) > 1]
    return problems, len(ids)


def main():
    if sys.argv[1:] == ["--check"]:
        problems, n = check()
        for p in problems:
            print(p)
        print(f"{n} rule IDs, {len(problems)} problems")
        sys.exit(1 if problems else 0)
    if sys.argv[1:]:
        sys.exit(__doc__)
    for section in SECTIONS:
        (ROOT / section / "README.md").write_text(render_index(section))
        print(f"wrote {section}/README.md")


if __name__ == "__main__":
    main()
